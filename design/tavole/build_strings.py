"""Rebuilds design/tavole/strings.js from the app's catalogs (the source of truth since 3.3):
macos/Native/SubVision/Resources/locales/{en,it}/app.json -> STR[key] = [en, it].
Run after any change to the catalogs:  python3 -I design/tavole/build_strings.py"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LOC = ROOT / 'macos/Native/SubVision/Resources/locales'
en = json.loads((LOC / 'en/app.json').read_text(encoding='utf-8'))
it = json.loads((LOC / 'it/app.json').read_text(encoding='utf-8'))
lines = ['/* GENERATED by build_strings.py from macos/Native/SubVision/Resources/locales/{en,it}/app.json.',
         ' * Do not edit: change the catalogs, then run the script. STR[key] = [English, Italian];',
         ' * plurals are <key>.uno / <key>.altri, {{ }} are literal braces. */',
         'window.STR = {']
for k in sorted(en):
    lines.append(f'  {json.dumps(k)}: [{json.dumps(en[k], ensure_ascii=False)}, {json.dumps(it[k], ensure_ascii=False)}],')
lines.append('};')
(Path(__file__).parent / 'strings.js').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'strings.js: {len(en)} keys')
